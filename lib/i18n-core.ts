function interpolate(text: string, params: TranslationParams = {}): string { return text.replace(/\{([a-zA-Z][\w]*)\}/g, (original, key: string) => Object.hasOwn(params, key) ? String(params[key] ?? '') : original); }
/** Looks up an explicitly selected UI message. Interpolated values are never translated or recursively processed. */
export function translate(locale: Locale, text: string, params?: TranslationParams): string {
  const key = text.trim(); const whitespaceBefore = text.match(/^\s*/)?.[0] || ''; const whitespaceAfter = text.match(/\s*$/)?.[0] || '';
  if (!key) return text;
  const value = locale === 'en' ? EN_TRANSLATIONS[key] ?? key : key;
  return whitespaceBefore + interpolate(value, params) + whitespaceAfter;
}
