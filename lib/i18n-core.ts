export function translateSystemText(text: string, locale: Locale): string {
  if (text.includes("\n")) return text.split("\n").map(line => translateSystemText(line, locale)).join("\n");
  if (locale === 'vi') { const direct = VI_SYSTEM_TRANSLATIONS[text] ?? reverseTranslations[text]; if (direct !== undefined) return direct; for (const entry of reverseDynamicTranslations) { const match = entry.regex.exec(text); if (match) return interpolate(entry.value, Object.fromEntries(entry.names.map((name, index) => [name, match[index + 1]]))); } for (let index = text.indexOf(': '); index >= 0; index = text.indexOf(': ', index + 2)) { const tail = text.slice(index + 2); const localized = VI_SYSTEM_TRANSLATIONS[tail] ?? reverseTranslations[tail]; if (localized) return text.slice(0, index + 2) + localized; } return text; }
  const groupingReason = translateGroupingReason(text);
  if (groupingReason !== undefined) return groupingReason;
  const direct = EN_TRANSLATIONS[text.trim()];
  if (direct !== undefined) return translate(locale, text);
  for (const entry of dynamicTranslations) {
    const match = entry.regex.exec(text);
    if (match) return interpolate(entry.value, Object.fromEntries(entry.names.map((name, index) => [name, match[index + 1]])));
  }
  // A client-side upload error can have an original filename prefix.
  for (let index = text.indexOf(': '); index >= 0; index = text.indexOf(': ', index + 2)) {
    const tail = text.slice(index + 2); const translated = translateSystemTextExact(tail);
    if (translated !== tail) return text.slice(0, index + 2) + translated;
  }
  return text;
}
