export function formatDate(value: string, locale: Locale): string {
  const parsed = new Date(value); if (Number.isNaN(parsed.getTime())) return value;
  return new Intl.DateTimeFormat(locale === 'en' ? 'en-GB' : 'vi-VN', { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).format(parsed);
}

