function translateGroupingReason(text: string): string | undefined {
  let remainder = text.trim();
  const sentences: string[] = [];
  while (remainder) {
    const key = GROUPING_REASON_KEYS.find(value => remainder === value || remainder.startsWith(value + ' '));
    if (!key) return undefined;
    sentences.push(EN_TRANSLATIONS[key]);
    remainder = remainder.slice(key.length).trimStart();
  }
  return sentences.length > 1 ? sentences.join(' ') : undefined;
}
